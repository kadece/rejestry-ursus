#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# update.sh — odświeżenie wykazów Ursus
#
# Pobiera PDF-y / XLSX-y ze strony ursus.um.warszawa.pl, przebudowuje
# data/*.json oraz site/index.html, commituje i wypycha na GitHub.
#
# Użycie:
#   ./update.sh              # pełna aktualizacja (pobierz + zbuduj + push)
#   ./update.sh --dry-run    # wszystko oprócz commita i pusha
#
# Zmienne środowiskowe:
#   PYTHON      interpreter Pythona (domyślnie: python3)
#   MIN_TOTAL   minimalna akceptowalna liczba pozycji (domyślnie: 4500)
#   MIN_YEARS   minimalna akceptowalna liczba roczników (domyślnie: 8)
#
# Kody wyjścia:
#   0  sukces (także "bez zmian")
#   1  build nie powiódł się całkowicie
#   2  wynik poniżej progu jakości — nic nie zacommitowano
# ---------------------------------------------------------------------------
set -uo pipefail

cd "$(dirname "$0")" || exit 1

PY=${PYTHON:-python3}
MIN_TOTAL=${MIN_TOTAL:-4500}
MIN_YEARS=${MIN_YEARS:-8}
LOG=build.log
DRY_RUN=0
[ "${1:-}" = "--dry-run" ] && DRY_RUN=1

say() { printf '%s %s\n' "$(date -Is)" "$*"; }

say "== start aktualizacji =="

# --- 1. pobranie danych i build --------------------------------------------
if ! $PY build.py --all 2>&1 | tee "$LOG"; then
  say "!! build.py --all nie powiodło się — próbuję tryb --render-only"
  if ! $PY build.py --all --render-only 2>&1 | tee -a "$LOG"; then
    say "!! --render-only też padło — przerywam"
    exit 1
  fi
  say "!! UWAGA: dane NIE zostały odświeżone, tylko strona przebudowana z cache"
fi

# --- 2. kontrola jakości ---------------------------------------------------
read -r TOTAL YEARS <<< "$(awk '/RAZEM:/ {t=$2; y=$5} END {print t, y}' "$LOG")"
TOTAL=${TOTAL:-0}
YEARS=${YEARS:-0}
say "   pozycji: $TOTAL w $YEARS rocznikach"

if [ "$TOTAL" -lt "$MIN_TOTAL" ] || [ "$YEARS" -lt "$MIN_YEARS" ]; then
  say "!! wynik poniżej progu (MIN_TOTAL=$MIN_TOTAL, MIN_YEARS=$MIN_YEARS)"
  say "!! NIE commituję — sprawdź $LOG"
  exit 2
fi

# --- 3. commit i push ------------------------------------------------------
git add -A data site build.log

if git diff --cached --quiet; then
  say "== bez zmian — nic do wypchnięcia =="
  exit 0
fi

if [ "$DRY_RUN" = "1" ]; then
  say "== --dry-run: zmiany przygotowane, ale nie commitowane =="
  git diff --cached --stat
  exit 0
fi

git commit -q \
  -m "Aktualizacja wykazów $(date +%F)" \
  -m "Pozycji: $TOTAL w $YEARS rocznikach." \
  -m "Generated by Mistral Vibe." \
  -m "Co-Authored-By: Mistral Vibe <vibe@mistral.ai>"

if ! git push -q origin HEAD; then
  say "!! git push nie powiódł się — commit jest lokalnie, sprawdź dostęp do GitHuba"
  exit 1
fi

say "== wypchnięto: $(git log -1 --format='%h %s') =="
